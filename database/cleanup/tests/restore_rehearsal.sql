-- SCRUM-434: rehearsal of 04_restore_from_backups.sql on the disposable schema CLEANUP_REHEARSAL
-- (created by restore_rehearsal_admin.sql). Run connected as CLEANUP_REHEARSAL, never on
-- DEVELOPMENT or PRODUCTION. Each "step" is run in order; the check steps return RESULT = PASS.
--
--   1. baseline          The copy is clean (01 returns no rows) and has the 14 backups.
--   2. activity          Activity after the cleanup: a new projection with a client purchase, and
--                        a sale of a seat that one of the deleted tickets used (a conflict).
--   3. (run 04)          Must FAIL: the deleted ticket can't come back to a seat sold again.
--   4. check_untouched   Nothing was restored, triggers and identities are back, activity kept.
--   5. resolve_conflict  The newer sale of that seat is removed (the decision a real restore
--                        would take with the business before running 04 again).
--   6. (run 04)          Must succeed.
--   7. check_restored    Every backed-up row is back with its original NULLs, the activity of
--                        step 2 survived, and triggers and identities are back.
--   8. (run 01)          Lists the original incomplete records again.
--   9. (run 03, then 01) The cleanup runs again on the restored data: 01 returns no rows.

-- step: baseline
SELECT CASE WHEN (SELECT COUNT(*) FROM USER_TABLES WHERE TABLE_NAME LIKE 'BKP434\_%' ESCAPE '\') = 14
             AND (SELECT COUNT(*) FROM TICKETS WHERE INVOICE_ID IS NULL) = 0
             AND (SELECT COUNT(*) FROM EMPLOYEES WHERE CREATED_AT IS NULL OR HIRE_DATE IS NULL) = 0
             AND (SELECT COUNT(*) FROM BKP434_EMPLOYEES WHERE CREATED_AT IS NULL) > 0
            THEN 'PASS' ELSE 'FAIL' END AS RESULT,
       (SELECT COUNT(*) FROM USER_TABLES WHERE TABLE_NAME LIKE 'BKP434\_%' ESCAPE '\') AS BACKUPS,
       (SELECT COUNT(*) FROM BKP434_TICKETS WHERE INVOICE_ID IS NULL) AS BACKED_UP_LOOSE_TICKETS
  FROM DUAL;

-- step: activity
CREATE TABLE REHEARSAL_MARKERS (NAME VARCHAR2(30) PRIMARY KEY, ID NUMBER NOT NULL);

DECLARE
    v_function NUMBER;
    v_invoice  NUMBER;
    v_ticket   NUMBER;
    v_theater  NUMBER;
    v_row      NUMBER;
    v_column   NUMBER;
    v_slot     NUMBER;

    PROCEDURE mark(p_name VARCHAR2, p_id NUMBER) IS
    BEGIN
        INSERT INTO REHEARSAL_MARKERS (NAME, ID) VALUES (p_name, p_id);
    END;

    -- A paid client purchase of one ticket; returns the invoice and ticket ids.
    PROCEDURE sell(p_function NUMBER, p_theater NUMBER, p_row NUMBER, p_column NUMBER,
                   p_invoice OUT NUMBER, p_ticket OUT NUMBER) IS
    BEGIN
        INSERT INTO INVOICES (CLIENT_ID, MOVIE_FUNCTION_ID, STATUS, PAYMENT_METHOD, TOTAL)
        VALUES ((SELECT MIN(CLIENT_ID) FROM CLIENTS WHERE STATUS = 'ACTIVE'), p_function, 'PAID', 'SIMULATED', 3500)
        RETURNING INVOICE_ID INTO p_invoice;
        INSERT INTO INVOICE_PRODUCTS (INVOICE_ID, PRODUCT_ID, QUANTITY, UNIT_PRICE)
        VALUES (p_invoice, (SELECT MIN(PRODUCT_ID) FROM PRODUCTS WHERE PRODUCT_TYPE = 'TICKET'), 1, 3500);
        INSERT INTO TICKETS (MOVIE_FUNCTION_ID, THEATER_ID, SEAT_ROW, SEAT_COLUMN, INVOICE_ID, PRODUCT_ID)
        VALUES (p_function, p_theater, p_row, p_column, p_invoice,
                (SELECT MIN(PRODUCT_ID) FROM PRODUCTS WHERE PRODUCT_TYPE = 'TICKET'))
        RETURNING TICKETS_ID INTO p_ticket;
    END;
BEGIN
    -- A new projection of a movie that survived the cleanup, in a far-away free slot, with a sale.
    SELECT f.THEATER_ID INTO v_theater FROM MOVIE_FUNCTIONS f
     WHERE EXISTS (SELECT 1 FROM SEATS s WHERE s.THEATER_ID = f.THEATER_ID)
     ORDER BY f.MOVIE_FUNCTION_ID FETCH FIRST 1 ROW ONLY;
    INSERT INTO MOVIE_FUNCTIONS (MOVIE_ID, THEATER_ID, START_TIME, END_TIME, SCREENING_DATE, CREATED_BY,
                                 PRICE, STATUS, PROJECTION_FORMAT, TECHNOLOGY, IS_PREMIERE)
    VALUES ((SELECT MIN(MOVIE_ID) FROM MOVIES), v_theater, TIMESTAMP '2030-01-15 10:00:00',
            TIMESTAMP '2030-01-15 13:00:00', DATE '2030-01-15',
            (SELECT MIN(e.EMPLOYEE_ID) FROM EMPLOYEES e JOIN EMPLOYEE_LOCAL_CREDENTIALS c ON c.EMPLOYEE_ID = e.EMPLOYEE_ID),
            3500, 'ACTIVE', '2D', 'STANDARD', 0)
    RETURNING MOVIE_FUNCTION_ID INTO v_function;
    SELECT ROW_NUMBER, COLUMN_NUMBER INTO v_row, v_column FROM SEATS
     WHERE THEATER_ID = v_theater ORDER BY ROW_NUMBER, COLUMN_NUMBER FETCH FIRST 1 ROW ONLY;
    sell(v_function, v_theater, v_row, v_column, v_invoice, v_ticket);
    mark('NEW_FUNCTION', v_function);
    mark('NEW_INVOICE', v_invoice);
    mark('NEW_TICKET', v_ticket);

    -- A sale of a seat that a deleted ticket used, in a projection that still exists.
    SELECT b.MOVIE_FUNCTION_ID, b.THEATER_ID, b.SEAT_ROW, b.SEAT_COLUMN
      INTO v_slot, v_theater, v_row, v_column
      FROM BKP434_TICKETS b
     WHERE b.INVOICE_ID IS NULL
       AND EXISTS (SELECT 1 FROM MOVIE_FUNCTIONS f WHERE f.MOVIE_FUNCTION_ID = b.MOVIE_FUNCTION_ID)
       AND NOT EXISTS (SELECT 1 FROM TICKETS t WHERE t.MOVIE_FUNCTION_ID = b.MOVIE_FUNCTION_ID
                          AND t.SEAT_ROW = b.SEAT_ROW AND t.SEAT_COLUMN = b.SEAT_COLUMN)
     ORDER BY b.TICKETS_ID FETCH FIRST 1 ROW ONLY;
    sell(v_slot, v_theater, v_row, v_column, v_invoice, v_ticket);
    mark('CONFLICT_INVOICE', v_invoice);
    mark('CONFLICT_TICKET', v_ticket);
    COMMIT;
END;
/

-- step: check_untouched
SELECT CASE WHEN (SELECT COUNT(*) FROM TICKETS WHERE INVOICE_ID IS NULL) = 0
             AND (SELECT COUNT(*) FROM EMPLOYEES WHERE CREATED_AT IS NULL OR HIRE_DATE IS NULL) = 0
             AND (SELECT COUNT(*) FROM BKP434_MOVIES b WHERE NOT EXISTS (SELECT 1 FROM MOVIES m WHERE m.MOVIE_ID = b.MOVIE_ID)) > 0
             AND (SELECT COUNT(*) FROM USER_TRIGGERS WHERE TRIGGER_NAME IN ('TRG_CLIENTS_REQUIRED_DATES', 'TRG_EMPLOYEES_REQUIRED_DATES') AND STATUS = 'ENABLED') = 2
             AND (SELECT COUNT(*) FROM USER_TAB_IDENTITY_COLS WHERE TABLE_NAME IN ('COMPANIES', 'EMPLOYEES', 'MOVIES', 'PASSWORD_RECOVERIES') AND GENERATION_TYPE = 'ALWAYS') = 4
             AND (SELECT COUNT(*) FROM REHEARSAL_MARKERS r WHERE r.NAME = 'NEW_FUNCTION' AND EXISTS (SELECT 1 FROM MOVIE_FUNCTIONS f WHERE f.MOVIE_FUNCTION_ID = r.ID)) = 1
             AND (SELECT COUNT(*) FROM REHEARSAL_MARKERS r WHERE r.NAME = 'CONFLICT_TICKET' AND EXISTS (SELECT 1 FROM TICKETS t WHERE t.TICKETS_ID = r.ID)) = 1
            THEN 'PASS' ELSE 'FAIL' END AS RESULT
  FROM DUAL;

-- step: resolve_conflict
DELETE FROM TICKETS WHERE TICKETS_ID = (SELECT ID FROM REHEARSAL_MARKERS WHERE NAME = 'CONFLICT_TICKET');
DELETE FROM INVOICE_PRODUCTS WHERE INVOICE_ID = (SELECT ID FROM REHEARSAL_MARKERS WHERE NAME = 'CONFLICT_INVOICE');
DELETE FROM INVOICES WHERE INVOICE_ID = (SELECT ID FROM REHEARSAL_MARKERS WHERE NAME = 'CONFLICT_INVOICE');
COMMIT;

-- step: check_restored
SELECT CASE WHEN missing = 0 AND nulls_match = 4 AND activity_kept = 3 AND rules_back = 6 AND identities_ahead = 4
            THEN 'PASS' ELSE 'FAIL' END AS RESULT,
       missing AS MISSING_BACKUP_ROWS, nulls_match AS NULL_COLUMNS_RESTORED, activity_kept AS ACTIVITY_ROWS_KEPT,
       rules_back AS TRIGGERS_AND_IDENTITIES_BACK, identities_ahead AS IDENTITIES_AHEAD_OF_MAX_ID
  FROM (SELECT
        (SELECT COUNT(*) FROM BKP434_COMPANIES b WHERE NOT EXISTS (SELECT 1 FROM COMPANIES t WHERE t.COMPANY_ID = b.COMPANY_ID))
      + (SELECT COUNT(*) FROM BKP434_CLIENTS b WHERE NOT EXISTS (SELECT 1 FROM CLIENTS t WHERE t.CLIENT_ID = b.CLIENT_ID))
      + (SELECT COUNT(*) FROM BKP434_EMPLOYEES b WHERE NOT EXISTS (SELECT 1 FROM EMPLOYEES t WHERE t.EMPLOYEE_ID = b.EMPLOYEE_ID))
      + (SELECT COUNT(*) FROM BKP434_MOVIES b WHERE NOT EXISTS (SELECT 1 FROM MOVIES t WHERE t.MOVIE_ID = b.MOVIE_ID))
      + (SELECT COUNT(*) FROM BKP434_MOVIE_GENRES b WHERE NOT EXISTS (SELECT 1 FROM MOVIE_GENRES t WHERE t.MOVIE_ID = b.MOVIE_ID AND t.GENRE_ID = b.GENRE_ID))
      + (SELECT COUNT(*) FROM BKP434_MOVIE_LANGUAGES b WHERE NOT EXISTS (SELECT 1 FROM MOVIE_LANGUAGES t WHERE t.MOVIE_ID = b.MOVIE_ID AND t.LANGUAGE_ID = b.LANGUAGE_ID))
      + (SELECT COUNT(*) FROM BKP434_CINEMA_MOVIES b WHERE NOT EXISTS (SELECT 1 FROM CINEMA_MOVIES t WHERE t.BRANCH_ID = b.BRANCH_ID AND t.MOVIE_ID = b.MOVIE_ID))
      + (SELECT COUNT(*) FROM BKP434_MOVIE_FUNCTIONS b WHERE NOT EXISTS (SELECT 1 FROM MOVIE_FUNCTIONS t WHERE t.MOVIE_FUNCTION_ID = b.MOVIE_FUNCTION_ID))
      + (SELECT COUNT(*) FROM BKP434_MOVIE_FUNCTIONS_ACTIVITIES b WHERE NOT EXISTS (SELECT 1 FROM MOVIE_FUNCTIONS_ACTIVITIES t WHERE t.MOVIE_FUNCTIONS_ACTIVITY_ID = b.MOVIE_FUNCTIONS_ACTIVITY_ID))
      + (SELECT COUNT(*) FROM BKP434_INVOICES b WHERE NOT EXISTS (SELECT 1 FROM INVOICES t WHERE t.INVOICE_ID = b.INVOICE_ID))
      + (SELECT COUNT(*) FROM BKP434_INVOICE_PRODUCTS b WHERE NOT EXISTS (SELECT 1 FROM INVOICE_PRODUCTS t WHERE t.INVOICE_ID = b.INVOICE_ID AND t.PRODUCT_ID = b.PRODUCT_ID))
      + (SELECT COUNT(*) FROM BKP434_PURCHASE_TICKET_EMAILS b WHERE NOT EXISTS (SELECT 1 FROM PURCHASE_TICKET_EMAILS t WHERE t.INVOICE_ID = b.INVOICE_ID))
      + (SELECT COUNT(*) FROM BKP434_TICKETS b WHERE NOT EXISTS (SELECT 1 FROM TICKETS t WHERE t.TICKETS_ID = b.TICKETS_ID))
      + (SELECT COUNT(*) FROM BKP434_PASSWORD_RECOVERIES b WHERE NOT EXISTS (SELECT 1 FROM PASSWORD_RECOVERIES t WHERE t.RECOVERY_ID = b.RECOVERY_ID)) AS missing,
        DECODE((SELECT COUNT(*) FROM CLIENTS WHERE CREATED_AT IS NULL), (SELECT COUNT(*) FROM BKP434_CLIENTS WHERE CREATED_AT IS NULL), 1, 0)
      + DECODE((SELECT COUNT(*) FROM EMPLOYEES WHERE CREATED_AT IS NULL), (SELECT COUNT(*) FROM BKP434_EMPLOYEES WHERE CREATED_AT IS NULL), 1, 0)
      + DECODE((SELECT COUNT(*) FROM EMPLOYEES WHERE HIRE_DATE IS NULL), (SELECT COUNT(*) FROM BKP434_EMPLOYEES WHERE HIRE_DATE IS NULL), 1, 0)
      + DECODE((SELECT COUNT(*) FROM MOVIE_FUNCTIONS WHERE PROJECTION_FORMAT IS NULL), (SELECT COUNT(*) FROM BKP434_MOVIE_FUNCTIONS WHERE PROJECTION_FORMAT IS NULL), 1, 0) AS nulls_match,
        (SELECT COUNT(*) FROM REHEARSAL_MARKERS r WHERE r.NAME = 'NEW_FUNCTION' AND EXISTS (SELECT 1 FROM MOVIE_FUNCTIONS t WHERE t.MOVIE_FUNCTION_ID = r.ID))
      + (SELECT COUNT(*) FROM REHEARSAL_MARKERS r WHERE r.NAME = 'NEW_INVOICE' AND EXISTS (SELECT 1 FROM INVOICES t WHERE t.INVOICE_ID = r.ID))
      + (SELECT COUNT(*) FROM REHEARSAL_MARKERS r WHERE r.NAME = 'NEW_TICKET' AND EXISTS (SELECT 1 FROM TICKETS t WHERE t.TICKETS_ID = r.ID)) AS activity_kept,
        (SELECT COUNT(*) FROM USER_TRIGGERS WHERE TRIGGER_NAME IN ('TRG_CLIENTS_REQUIRED_DATES', 'TRG_EMPLOYEES_REQUIRED_DATES') AND STATUS = 'ENABLED')
      + (SELECT COUNT(*) FROM USER_TAB_IDENTITY_COLS WHERE TABLE_NAME IN ('COMPANIES', 'EMPLOYEES', 'MOVIES', 'PASSWORD_RECOVERIES') AND GENERATION_TYPE = 'ALWAYS') AS rules_back,
        (SELECT COUNT(*) FROM USER_TAB_IDENTITY_COLS i JOIN USER_SEQUENCES s ON s.SEQUENCE_NAME = i.SEQUENCE_NAME
          WHERE (i.TABLE_NAME = 'COMPANIES' AND s.LAST_NUMBER > (SELECT MAX(COMPANY_ID) FROM COMPANIES))
             OR (i.TABLE_NAME = 'EMPLOYEES' AND s.LAST_NUMBER > (SELECT MAX(EMPLOYEE_ID) FROM EMPLOYEES))
             OR (i.TABLE_NAME = 'MOVIES' AND s.LAST_NUMBER > (SELECT MAX(MOVIE_ID) FROM MOVIES))
             OR (i.TABLE_NAME = 'PASSWORD_RECOVERIES' AND s.LAST_NUMBER > (SELECT MAX(RECOVERY_ID) FROM PASSWORD_RECOVERIES))) AS identities_ahead
          FROM DUAL);
