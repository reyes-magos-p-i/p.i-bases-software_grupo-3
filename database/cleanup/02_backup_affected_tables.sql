-- SCRUM-434: copies every table that 03 changes to BKP434_<table>, before the cleanup.
-- Run as the schema owner (DEVELOPMENT or PRODUCTION) with Run Script (F5).
-- It refuses to run if a backup already exists, so a second run never overwrites the first copy.
-- To undo the cleanup from these backups, run 04_restore_from_backups.sql (never DELETE and
-- re-insert whole tables: other rows still reference them).
SET SERVEROUTPUT ON

DECLARE
    TYPE name_list IS TABLE OF VARCHAR2(128);
    tables name_list := name_list('COMPANIES', 'CLIENTS', 'EMPLOYEES', 'PASSWORD_RECOVERIES',
                                  'MOVIES', 'MOVIE_GENRES', 'MOVIE_LANGUAGES', 'CINEMA_MOVIES',
                                  'MOVIE_FUNCTIONS', 'MOVIE_FUNCTIONS_ACTIVITIES', 'TICKETS',
                                  'INVOICES', 'INVOICE_PRODUCTS', 'PURCHASE_TICKET_EMAILS');
    existing NUMBER;
BEGIN
    SELECT COUNT(*) INTO existing FROM USER_TABLES WHERE TABLE_NAME LIKE 'BKP434\_%' ESCAPE '\';
    IF existing > 0 THEN
        RAISE_APPLICATION_ERROR(-20434,
            'Ya existen respaldos BKP434_ en este esquema. Revísalos antes de crear otros.');
    END IF;

    FOR i IN 1 .. tables.COUNT LOOP
        EXECUTE IMMEDIATE 'CREATE TABLE BKP434_' || tables(i) || ' AS SELECT * FROM ' || tables(i);
        DBMS_OUTPUT.PUT_LINE('Respaldo creado: BKP434_' || tables(i));
    END LOOP;
END;
/

-- Every backup must have the same row count as its table (UT-026 / UT-030).
SELECT 'COMPANIES' AS TABLE_NAME, (SELECT COUNT(*) FROM COMPANIES) AS ORIGINAL_ROWS,
       (SELECT COUNT(*) FROM BKP434_COMPANIES) AS BACKUP_ROWS FROM DUAL
UNION ALL SELECT 'CLIENTS', (SELECT COUNT(*) FROM CLIENTS), (SELECT COUNT(*) FROM BKP434_CLIENTS) FROM DUAL
UNION ALL SELECT 'EMPLOYEES', (SELECT COUNT(*) FROM EMPLOYEES), (SELECT COUNT(*) FROM BKP434_EMPLOYEES) FROM DUAL
UNION ALL SELECT 'PASSWORD_RECOVERIES', (SELECT COUNT(*) FROM PASSWORD_RECOVERIES),
                 (SELECT COUNT(*) FROM BKP434_PASSWORD_RECOVERIES) FROM DUAL
UNION ALL SELECT 'MOVIES', (SELECT COUNT(*) FROM MOVIES), (SELECT COUNT(*) FROM BKP434_MOVIES) FROM DUAL
UNION ALL SELECT 'MOVIE_GENRES', (SELECT COUNT(*) FROM MOVIE_GENRES), (SELECT COUNT(*) FROM BKP434_MOVIE_GENRES) FROM DUAL
UNION ALL SELECT 'MOVIE_LANGUAGES', (SELECT COUNT(*) FROM MOVIE_LANGUAGES),
                 (SELECT COUNT(*) FROM BKP434_MOVIE_LANGUAGES) FROM DUAL
UNION ALL SELECT 'CINEMA_MOVIES', (SELECT COUNT(*) FROM CINEMA_MOVIES), (SELECT COUNT(*) FROM BKP434_CINEMA_MOVIES) FROM DUAL
UNION ALL SELECT 'INVOICES', (SELECT COUNT(*) FROM INVOICES), (SELECT COUNT(*) FROM BKP434_INVOICES) FROM DUAL
UNION ALL SELECT 'INVOICE_PRODUCTS', (SELECT COUNT(*) FROM INVOICE_PRODUCTS),
                 (SELECT COUNT(*) FROM BKP434_INVOICE_PRODUCTS) FROM DUAL
UNION ALL SELECT 'PURCHASE_TICKET_EMAILS', (SELECT COUNT(*) FROM PURCHASE_TICKET_EMAILS),
                 (SELECT COUNT(*) FROM BKP434_PURCHASE_TICKET_EMAILS) FROM DUAL
UNION ALL SELECT 'MOVIE_FUNCTIONS', (SELECT COUNT(*) FROM MOVIE_FUNCTIONS),
                 (SELECT COUNT(*) FROM BKP434_MOVIE_FUNCTIONS) FROM DUAL
UNION ALL SELECT 'MOVIE_FUNCTIONS_ACTIVITIES', (SELECT COUNT(*) FROM MOVIE_FUNCTIONS_ACTIVITIES),
                 (SELECT COUNT(*) FROM BKP434_MOVIE_FUNCTIONS_ACTIVITIES) FROM DUAL
UNION ALL SELECT 'TICKETS', (SELECT COUNT(*) FROM TICKETS), (SELECT COUNT(*) FROM BKP434_TICKETS) FROM DUAL;
