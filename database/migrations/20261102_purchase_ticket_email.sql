-- SCRUM-323: durable ticket-email requests; apply before deploying the API.
-- SMTP runs outside the purchase transaction. Failed or uncertain sends are not retried automatically.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET DEFINE OFF

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_TABLES
     WHERE OWNER = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
       AND TABLE_NAME = 'PURCHASE_TICKET_EMAILS';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE PURCHASE_TICKET_EMAILS (
                INVOICE_ID NUMBER NOT NULL,
                RECIPIENT_EMAIL VARCHAR2(150 CHAR) NOT NULL,
                STATUS VARCHAR2(10 BYTE) DEFAULT 'PENDING' NOT NULL,
                ATTEMPT_ID VARCHAR2(36 BYTE) NOT NULL,
                ATTEMPTS NUMBER(10) DEFAULT 0 NOT NULL,
                REQUESTED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                SENT_AT TIMESTAMP WITH TIME ZONE,
                CONSTRAINT PK_PURCHASE_TICKET_EMAILS PRIMARY KEY (INVOICE_ID),
                CONSTRAINT FK_TICKET_EMAIL_INVOICE FOREIGN KEY (INVOICE_ID) REFERENCES INVOICES (INVOICE_ID),
                CONSTRAINT CK_TICKET_EMAIL_STATUS CHECK (STATUS IN ('PENDING','SENDING','SENT','FAILED','UNKNOWN')),
                CONSTRAINT CK_TICKET_EMAIL_ATTEMPTS CHECK (ATTEMPTS >= 0)
            )]';
    END IF;
    SELECT COUNT(*) INTO v_count FROM ALL_INDEXES
     WHERE OWNER = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
       AND INDEX_NAME = 'IX_TICKET_EMAIL_PENDING';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_TICKET_EMAIL_PENDING ON PURCHASE_TICKET_EMAILS (STATUS,REQUESTED_AT)';
    END IF;
END;
/
