-- SCRUM-304: client refund requests for tickets whose projection was cancelled.
-- Records the request only; the payment refund itself is not executed here.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET DEFINE OFF

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_TABLES
     WHERE OWNER = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
       AND TABLE_NAME = 'TICKET_REFUND_REQUESTS';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE TICKET_REFUND_REQUESTS (
                TICKET_ID NUMBER NOT NULL,
                STATUS VARCHAR2(10 BYTE) DEFAULT 'REQUESTED' NOT NULL,
                REQUESTED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT PK_TICKET_REFUND_REQUESTS PRIMARY KEY (TICKET_ID),
                CONSTRAINT FK_TICKET_REFUND_TICKET FOREIGN KEY (TICKET_ID) REFERENCES TICKETS (TICKETS_ID),
                CONSTRAINT CK_TICKET_REFUND_STATUS CHECK (STATUS IN ('REQUESTED'))
            )]';
    END IF;
END;
/
