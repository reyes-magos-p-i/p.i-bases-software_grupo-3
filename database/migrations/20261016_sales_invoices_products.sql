-- =========================================================
-- SCRUM-17 / SCRUM-18 / SCRUM-347: sales (invoices and products)
--
-- Run connected as PRODUCTION (or with CURRENT_SCHEMA = PRODUCTION).
-- None of these tables existed before this migration.
--
-- TICKETS is not created here: PRODUCTION already has it (TICKETS_ID,
-- MOVIE_FUNCTION_ID, SEAT_ID), made by the seat and ticket stories. The
-- number of tickets of an invoice is the QUANTITY of its TICKET lines;
-- linking each ticket to its invoice is left to the purchase flow.
--
-- One invoice is one purchase for one movie function. The same row is
-- shown to the administrator as a transaction (FAC-000123) and to the
-- client as an order (ORD-000123): both numbers are
-- LPAD(invoice_id, 6, '0') with a different prefix, so no extra column
-- is stored for them.
-- =========================================================

-- ---------------------------------------------------------
-- 1. Products: generic catalog of what can be sold for a function
--    TICKET: a seat for the function. Its price is the PRICE of the
--            movie function, so the product has no price of its own.
--    FOOD:   snacks and drinks with a fixed catalog price.
-- ---------------------------------------------------------
CREATE TABLE Products (
    product_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR2(100) NOT NULL,
    product_type    VARCHAR2(10) NOT NULL,
    price           NUMBER(10, 2),
    CONSTRAINT uq_products_name UNIQUE (name),
    CONSTRAINT chk_products_type
        CHECK (product_type IN ('TICKET', 'FOOD')),
    CONSTRAINT chk_products_price
        CHECK (
            (product_type = 'TICKET' AND price IS NULL)
            OR (product_type = 'FOOD' AND price >= 0)
        )
);

-- ---------------------------------------------------------
-- 2. Invoices: purchase header
--    TOTAL is stored as charged; the API keeps it equal to the sum of
--    QUANTITY * UNIT_PRICE of its lines. Stripe receives it in the
--    smallest currency unit (CRC has 2 decimals: 3500.00 -> 350000).
--
--    Card payments go through Stripe (test mode for now):
--      PENDING   the invoice and its PaymentIntent exist, payment not
--                confirmed yet.
--      PAID      the payment_intent.succeeded webhook confirmed it.
--      FAILED    the payment was declined or abandoned.
--      CANCELLED cancelled after creation (e.g. the function was
--                cancelled).
--    The transaction list and the purchase history only show PAID and
--    CANCELLED invoices. Cash (box office) invoices are created already
--    PAID and have no Stripe data.
--
--    STRIPE_PAYMENT_INTENT_ID is unique, so a repeated webhook can never
--    apply the same payment twice. STRIPE_LIVEMODE separates test-mode
--    payments (0) from real ones (1) in the same database. Only the card
--    brand (as Stripe returns it, e.g. 'visa') and its last 4 digits are
--    stored, never the card number; they are known once the payment
--    succeeds.
-- ---------------------------------------------------------
CREATE TABLE Invoices (
    invoice_id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id                   NUMBER NOT NULL,
    movie_function_id           NUMBER NOT NULL,
    created_at                  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    status                      VARCHAR2(10) DEFAULT 'PENDING' NOT NULL,
    payment_method              VARCHAR2(10) NOT NULL,
    stripe_payment_intent_id    VARCHAR2(255),
    stripe_livemode             NUMBER(1),
    card_brand                  VARCHAR2(20),
    card_last4                  CHAR(4),
    total                       NUMBER(12, 2) NOT NULL,
    CONSTRAINT fk_invoice_client
        FOREIGN KEY (client_id) REFERENCES Clients (client_id),
    CONSTRAINT fk_invoice_movie_function
        FOREIGN KEY (movie_function_id) REFERENCES Movie_functions (movie_function_id),
    -- Target of the Tickets composite key: a ticket is always for the
    -- same function as its invoice.
    CONSTRAINT uq_invoice_function UNIQUE (invoice_id, movie_function_id),
    CONSTRAINT uq_invoice_payment_intent UNIQUE (stripe_payment_intent_id),
    CONSTRAINT chk_invoice_status
        CHECK (status IN ('PENDING', 'PAID', 'FAILED', 'CANCELLED')),
    CONSTRAINT chk_invoice_card_last4
        CHECK (card_last4 IS NULL OR REGEXP_LIKE(card_last4, '^[0-9]{4}$')),
    CONSTRAINT chk_invoice_payment
        CHECK (
            (payment_method = 'CARD'
                AND stripe_payment_intent_id IS NOT NULL
                AND stripe_livemode IN (0, 1)
                AND (status <> 'PAID'
                    OR (card_brand IS NOT NULL AND card_last4 IS NOT NULL)))
            OR (payment_method = 'CASH'
                AND status IN ('PAID', 'CANCELLED')
                AND stripe_payment_intent_id IS NULL
                AND stripe_livemode IS NULL
                AND card_brand IS NULL
                AND card_last4 IS NULL)
        ),
    CONSTRAINT chk_invoice_total
        CHECK (total >= 0)
);

-- Client purchase history (own invoices, newest first).
CREATE INDEX ix_invoices_client_created
    ON Invoices (client_id, created_at);

-- Administrator transaction list (all invoices, newest first).
CREATE INDEX ix_invoices_created
    ON Invoices (created_at);

-- ---------------------------------------------------------
-- 3. Invoice_products: invoice lines
--    UNIT_PRICE is the price actually charged, so later catalog or
--    function price changes do not alter past invoices.
-- ---------------------------------------------------------
CREATE TABLE Invoice_products (
    invoice_id      NUMBER NOT NULL,
    product_id      NUMBER NOT NULL,
    quantity        NUMBER(3) NOT NULL,
    unit_price      NUMBER(10, 2) NOT NULL,
    CONSTRAINT pk_invoice_products PRIMARY KEY (invoice_id, product_id),
    CONSTRAINT fk_invoice_products_invoice
        FOREIGN KEY (invoice_id) REFERENCES Invoices (invoice_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_invoice_products_product
        FOREIGN KEY (product_id) REFERENCES Products (product_id),
    CONSTRAINT chk_invoice_products_quantity
        CHECK (quantity > 0),
    CONSTRAINT chk_invoice_products_price
        CHECK (unit_price >= 0)
);

