-- SCRUM-378: buyers can take any available seat unless a lower limit is configured.
-- 10000 is the largest theater, so availability is what limits a purchase by default.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET DEFINE OFF

ALTER TABLE GLOBAL_SETTINGS DROP CONSTRAINT CK_GLOBAL_SETTINGS_LIMITS;

ALTER TABLE GLOBAL_SETTINGS ADD CONSTRAINT CK_GLOBAL_SETTINGS_LIMITS CHECK (
    SETTING_KEY NOT IN ('MAX_TICKETS_PER_FUNCTION', 'MAX_GUEST_PURCHASES_PER_HOUR')
    OR (SETTING_VALUE BETWEEN 1 AND 10000 AND SETTING_VALUE = TRUNC(SETTING_VALUE))
);

UPDATE GLOBAL_SETTINGS
   SET SETTING_VALUE = 10000, UPDATED_AT = SYSTIMESTAMP
 WHERE SETTING_KEY = 'MAX_TICKETS_PER_FUNCTION' AND SETTING_VALUE = 10;
COMMIT;
