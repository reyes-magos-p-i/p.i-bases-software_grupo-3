-- SCRUM-378: business values that must change without a deploy; apply before deploying the API.
-- To change one: UPDATE GLOBAL_SETTINGS SET SETTING_VALUE = 12, UPDATED_AT = SYSTIMESTAMP
--                 WHERE SETTING_KEY = 'MAX_TICKETS_PER_FUNCTION'; COMMIT;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET DEFINE OFF

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_TABLES
     WHERE OWNER = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
       AND TABLE_NAME = 'GLOBAL_SETTINGS';
    IF v_count = 0 THEN
        -- Purchases lock their seats with a single IN list, and Oracle allows 1000 values.
        EXECUTE IMMEDIATE q'[
            CREATE TABLE GLOBAL_SETTINGS (
                SETTING_KEY VARCHAR2(40 BYTE) NOT NULL,
                SETTING_VALUE NUMBER(10,2) NOT NULL,
                DESCRIPTION VARCHAR2(200 CHAR),
                UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT PK_GLOBAL_SETTINGS PRIMARY KEY (SETTING_KEY),
                CONSTRAINT CK_GLOBAL_SETTINGS_VALUE CHECK (SETTING_VALUE >= 0),
                CONSTRAINT CK_GLOBAL_SETTINGS_LIMITS CHECK (
                    SETTING_KEY NOT IN ('MAX_TICKETS_PER_FUNCTION', 'MAX_GUEST_PURCHASES_PER_HOUR')
                    OR (SETTING_VALUE BETWEEN 1 AND 1000 AND SETTING_VALUE = TRUNC(SETTING_VALUE))
                )
            )]';
    END IF;
END;
/

MERGE INTO GLOBAL_SETTINGS target
USING (
    SELECT 'MAX_TICKETS_PER_FUNCTION' SETTING_KEY, 10 SETTING_VALUE,
           'Boletos que un comprador puede tener por función' DESCRIPTION FROM DUAL
    UNION ALL
    SELECT 'MAX_GUEST_PURCHASES_PER_HOUR', 3,
           'Compras de invitado por correo y hora' FROM DUAL
) source ON (target.SETTING_KEY = source.SETTING_KEY)
WHEN NOT MATCHED THEN INSERT (SETTING_KEY, SETTING_VALUE, DESCRIPTION)
VALUES (source.SETTING_KEY, source.SETTING_VALUE, source.DESCRIPTION);
COMMIT;
