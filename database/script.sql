-- Oracle triggers only fire on INSERT/UPDATE/DELETE, never at a given
-- time; a DBMS_SCHEDULER job runs every minute instead:
-- ACTIVE -> IN_PROGRESS when it starts and -> FINISHED when it ends.
CREATE OR REPLACE PROCEDURE refresh_movie_function_status AS
    v_now TIMESTAMP := CAST(SYSTIMESTAMP AT TIME ZONE 'America/Costa_Rica' AS TIMESTAMP);
BEGIN
    UPDATE Movie_functions
       SET status = 'IN_PROGRESS'
     WHERE status = 'ACTIVE'
       AND start_time <= v_now
       AND end_time > v_now;

    UPDATE Movie_functions
       SET status = 'FINISHED'
     WHERE status IN ('ACTIVE', 'IN_PROGRESS')
       AND end_time <= v_now;

    COMMIT;
END;
/

BEGIN
    DBMS_SCHEDULER.CREATE_JOB(
        job_name        => 'MOVIE_FUNCTION_STATUS_JOB',
        job_type        => 'STORED_PROCEDURE',
        job_action      => 'REFRESH_MOVIE_FUNCTION_STATUS',
        start_date      => SYSTIMESTAMP,
        repeat_interval => 'FREQ=MINUTELY;INTERVAL=1',
        enabled         => TRUE,
        comments        => 'Actualiza el estado de las proyecciones según su horario'
    );
END;
