CREATE TABLE Client_external_credentials (
    external_credentials_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id             NUMBER NOT NULL,
    provider_name         VARCHAR2(50) NOT NULL,
    provider_user_id      VARCHAR2(255) NOT NULL,
    email                 VARCHAR2(150),
    access_token          VARCHAR2(2000),
    refresh_token         VARCHAR2(2000),
    token_expires_at      TIMESTAMP,
    created_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_client_ext_cred_client
        FOREIGN KEY (client_id) REFERENCES Clients (client_id),
    CONSTRAINT chk_client_ext_provider
        CHECK (provider_name IN ('GOOGLE', 'FACEBOOK')),
    CONSTRAINT uq_client_ext_cred_client_provider
        UNIQUE (client_id, provider_name),
    CONSTRAINT uq_client_ext_cred_provider_account
        UNIQUE (provider_name, provider_user_id)
);

CREATE TABLE Client_local_credentials (
    credentials_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id       NUMBER NOT NULL UNIQUE,
    password_hash   VARCHAR2(255) NOT NULL,
    salt            VARCHAR2(100) NOT NULL,
    CONSTRAINT fk_client_local_cred_client
        FOREIGN KEY (client_id) REFERENCES Clients (client_id)
);

-- =========================================================
-- SECTION: Activities and Movie Functions
-- =========================================================
CREATE TABLE Activities (
    activity_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR2(100) NOT NULL,
    duration        INTERVAL DAY TO SECOND NOT NULL,
    type            VARCHAR2(50) NOT NULL,
    description     VARCHAR2(500),
    CONSTRAINT chk_activity_type
        CHECK (type IN ('CLEANING', 'MAINTENANCE', 'ADVERTISEMENT'))
);

CREATE TABLE Movie_functions (
    movie_function_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id            NUMBER NOT NULL,
    theater_id           NUMBER NOT NULL,
    start_time            TIMESTAMP NOT NULL,
    end_time              TIMESTAMP NOT NULL,
    screening_date         DATE NOT NULL,
    created_by             NUMBER NOT NULL,
    CONSTRAINT fk_movie_function_employee
        FOREIGN KEY (created_by) REFERENCES Employees (employee_id),
    CONSTRAINT fk_movie_function_movie
        FOREIGN KEY (movie_id) REFERENCES Movies (movie_id),
    CONSTRAINT fk_movie_function_theater
        FOREIGN KEY (theater_id) REFERENCES Theaters (theater_id),
    CONSTRAINT uq_movie_function UNIQUE (movie_id, theater_id, start_time, end_time),
    CONSTRAINT chk_movie_function_times
        CHECK (end_time > start_time)
);

CREATE TABLE Tickets (
    ticket_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_function_id   NUMBER NOT NULL,
    invoice_id          NUMBER NOT NULL,
    seat                VARCHAR2(10) NOT NULL,
    price_paid          NUMBER(12,2) NOT NULL,

    CONSTRAINT fk_ticket_movie_function
        FOREIGN KEY (movie_function_id)
        REFERENCES Movie_functions (movie_function_id),

    CONSTRAINT fk_ticket_invoice
        FOREIGN KEY (invoice_id)
        REFERENCES Invoices (invoice_id),

    CONSTRAINT uq_ticket_function_seat
        UNIQUE (movie_function_id, seat),

    CONSTRAINT chk_ticket_price_paid
        CHECK (price_paid >= 0)
);

CREATE TABLE Movie_functions_activities (
    movie_functions_activity_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_function_id            NUMBER NOT NULL,
    activity_id                  NUMBER NOT NULL,
    created_by                   NUMBER NOT NULL,
    CONSTRAINT fk_mfa_movie_function
        FOREIGN KEY (movie_function_id) REFERENCES Movie_functions (movie_function_id),
    CONSTRAINT fk_mfa_activity
        FOREIGN KEY (activity_id) REFERENCES Activities (activity_id),
    CONSTRAINT fk_mfa_employee
        FOREIGN KEY (created_by) REFERENCES Employees (employee_id),
    CONSTRAINT uq_mfa_function_activity
        UNIQUE (movie_function_id, activity_id)
);

CREATE TABLE Products (
    product_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(100),
    price NUMBER NOT NULL,
    is_ticket BOOLEAN NOT NULL,
    
);
