CREATE OR REPLACE TRIGGER trg_employees_required_dates
BEFORE INSERT OR UPDATE OF created_at, hire_date ON Employees
FOR EACH ROW
BEGIN
    IF (INSERTING OR UPDATING('CREATED_AT')) AND :NEW.created_at IS NULL THEN
        RAISE_APPLICATION_ERROR(-20001, 'La fecha de registro es obligatoria.');
    END IF;
    IF (INSERTING OR UPDATING('HIRE_DATE')) AND :NEW.hire_date IS NULL THEN
        RAISE_APPLICATION_ERROR(-20002, 'La fecha de contratación es obligatoria.');
    END IF;
    IF :NEW.hire_date IS NOT NULL AND :NEW.hire_date <> TRUNC(:NEW.hire_date) THEN
        RAISE_APPLICATION_ERROR(-20003, 'La fecha de contratación no debe contener una hora.');
    END IF;
END;
