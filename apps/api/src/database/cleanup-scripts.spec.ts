import { readFileSync } from 'node:fs';
import { join } from 'node:path';

// SCRUM-434: the cleanup and restore scripts run by hand in Oracle, so CI can't execute them.
// These checks keep the restore rules the review asked for: the full rehearsal is
// database/cleanup/tests/restore_rehearsal.sql on a disposable schema.
const root = join(process.cwd(), '..', '..', 'database');
const read = (file: string) => readFileSync(join(root, file), 'utf8');
const withoutComments = (sql: string) => sql.replace(/--.*$/gm, '');

const backup = read('cleanup/02_backup_affected_tables.sql');
const restore = read('cleanup/04_restore_from_backups.sql');
const rehearsalAdmin = read('cleanup/tests/restore_rehearsal_admin.sql');
const copyScript = read('environments/02_admin_copy_production_to_development.sql');

const quoted = (list: string) =>
  [...list.matchAll(/'([A-Z_]+)'/g)].map((match) => match[1]);
const restoreOrder = quoted(
  /restore_order SYS\.ODCIVARCHAR2LIST := SYS\.ODCIVARCHAR2LIST\(([^;]*)\);/.exec(
    restore,
  )?.[1] ?? '',
);
const backedUp = quoted(
  /tables name_list := name_list\(([^;]*)\);/.exec(backup)?.[1] ?? '',
);

// Foreign keys between the backed-up tables (parent, child), from the live schema.
const FOREIGN_KEYS: [string, string][] = [
  ['CLIENTS', 'INVOICES'],
  ['CLIENTS', 'PASSWORD_RECOVERIES'],
  ['EMPLOYEES', 'MOVIE_FUNCTIONS'],
  ['EMPLOYEES', 'MOVIE_FUNCTIONS_ACTIVITIES'],
  ['EMPLOYEES', 'PASSWORD_RECOVERIES'],
  ['MOVIES', 'MOVIE_GENRES'],
  ['MOVIES', 'MOVIE_LANGUAGES'],
  ['MOVIES', 'CINEMA_MOVIES'],
  ['MOVIES', 'MOVIE_FUNCTIONS'],
  ['MOVIE_FUNCTIONS', 'MOVIE_FUNCTIONS_ACTIVITIES'],
  ['MOVIE_FUNCTIONS', 'INVOICES'],
  ['MOVIE_FUNCTIONS', 'TICKETS'],
  ['INVOICES', 'INVOICE_PRODUCTS'],
  ['INVOICES', 'PURCHASE_TICKET_EMAILS'],
  ['INVOICES', 'TICKETS'],
  ['INVOICE_PRODUCTS', 'TICKETS'],
];

describe('Restore from the SCRUM-434 backups (04)', () => {
  it('restores exactly the tables 02 backs up', () => {
    expect(backedUp).toHaveLength(14);
    expect([...restoreOrder].sort()).toEqual([...backedUp].sort());
  });

  it.each(FOREIGN_KEYS)('inserts %s before %s', (parent, child) => {
    expect(restoreOrder.indexOf(parent)).toBeGreaterThan(-1);
    expect(restoreOrder.indexOf(parent)).toBeLessThan(
      restoreOrder.indexOf(child),
    );
  });

  it('never deletes rows, so rows created after the cleanup survive', () => {
    expect(withoutComments(restore)).not.toMatch(/\bDELETE\b|\bTRUNCATE\b/i);
    expect(restore).toContain('WHERE NOT EXISTS (SELECT 1 FROM ');
  });

  it('relaxes the date triggers and ALWAYS identities, then puts them back', () => {
    const code = withoutComments(restore);
    expect(code).toContain("'TRG_CLIENTS_REQUIRED_DATES'");
    expect(code).toContain("'TRG_EMPLOYEES_REQUIRED_DATES'");
    expect(code).toContain("' DISABLE'");
    expect(code).toContain("' ENABLE'");
    expect(code).toContain("' GENERATED BY DEFAULT AS IDENTITY'");
    expect(code).toContain(
      "' GENERATED ALWAYS AS IDENTITY (START WITH LIMIT VALUE)'",
    );
    expect(code).toMatch(/WHERE GENERATION_TYPE = 'ALWAYS'/);
  });

  it('rolls back the data and puts the rules back before raising on any error', () => {
    expect(withoutComments(restore)).toMatch(
      /WHEN OTHERS THEN\s+ROLLBACK;[\s\S]*?put_rules_back;\s+RAISE;/,
    );
  });

  it('fails when a trigger or identity could not be put back', () => {
    expect(restore).toMatch(
      /put_rules_back;\s+IF rules_failed > 0 THEN\s+RAISE_APPLICATION_ERROR/,
    );
  });

  it('runs serially, like the cleanup', () => {
    expect(restore).toContain('ALTER SESSION DISABLE PARALLEL DML;');
  });
});

describe('Restore rehearsal on a disposable schema', () => {
  it('copies DEVELOPMENT with the same checked Data Pump block as 02', () => {
    const block = (text: string) =>
      text.slice(
        text.indexOf('-- datapump:begin'),
        text.indexOf('-- datapump:end'),
      );
    expect(block(rehearsalAdmin)).toBe(block(copyScript));
    expect(rehearsalAdmin).toContain(
      "METADATA_REMAP(v_job, 'REMAP_SCHEMA', 'DEVELOPMENT', 'CLEANUP_REHEARSAL')",
    );
  });

  it('runs its steps in order, with a conflict before the successful restore', () => {
    const steps = [
      ...read('cleanup/tests/restore_rehearsal.sql').matchAll(
        /^-- step: (\w+)$/gm,
      ),
    ].map((match) => match[1]);
    expect(steps).toEqual([
      'baseline',
      'activity',
      'check_untouched',
      'resolve_conflict',
      'check_restored',
    ]);
  });
});
